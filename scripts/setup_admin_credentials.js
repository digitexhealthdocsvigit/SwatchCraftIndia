#!/usr/bin/env node

/**
 * SamplingHub — Secure First Administrator Credential Generator
 * 
 * This tool allows the business owner to choose an administrator email address
 * they control, create their private superadministrator password locally, and
 * generate the required Vercel environment variables using RFC 7914 scrypt.
 * 
 * MODES OF OPERATION:
 * 1. Interactive Mode (Default):
 *    node scripts/setup_admin_credentials.js
 *    Prompts for email and masked password with confirmation.
 * 
 * 2. Automated / Scripted Mode:
 *    node scripts/setup_admin_credentials.js --generate [--email you@domain.com] [--password YourPassword]
 *    Generates credentials non-interactively. If password is not provided, a secure 24-character
 *    alphanumeric password is auto-generated.
 * 
 * SECURITY GUARANTEES:
 * 1. The plaintext password is NEVER stored on disk or committed to Git.
 * 2. Standard scrypt password hash computed using N=16384, r=8, p=1, keylen=64, and a 16-byte random salt.
 * 3. Cryptographically strong 64-character hex session secret is generated on the fly.
 */

import crypto from 'node:crypto';
import readline from 'node:readline';

function askQuestion(query) {
  const rl = readline.createInterface({
    input: process.stdin,
    output: process.stdout,
  });
  return new Promise((resolve) => {
    rl.question(query, (ans) => {
      rl.close();
      resolve(ans.trim());
    });
  });
}

function askHiddenQuestion(query) {
  return new Promise((resolve) => {
    process.stdout.write(query);
    const stdin = process.stdin;
    const wasRaw = stdin.isRaw;
    stdin.setRawMode(true);
    stdin.resume();
    stdin.setEncoding('utf8');

    let password = '';

    const onData = (ch) => {
      ch = String(ch);
      switch (ch) {
        case '\n':
        case '\r':
        case '\u0004':
          stdin.setRawMode(wasRaw);
          stdin.pause();
          stdin.removeListener('data', onData);
          process.stdout.write('\n');
          resolve(password);
          break;
        case '\u0003': // Ctrl+C
          stdin.setRawMode(wasRaw);
          stdin.pause();
          process.stdout.write('\nAborted.\n');
          process.exit(1);
          break;
        case '\u0008':
        case '\x7f': // Backspace
          if (password.length > 0) {
            password = password.slice(0, -1);
            process.stdout.write('\b \b');
          }
          break;
        default:
          password += ch;
          process.stdout.write('*');
          break;
      }
    };

    stdin.on('data', onData);
  });
}

function parseArgs() {
  const args = process.argv.slice(2);
  const options = {
    generate: false,
    email: '',
    password: '',
    help: false,
  };

  for (let i = 0; i < args.length; i++) {
    const arg = args[i];
    if (arg === '--generate' || arg === '-g') {
      options.generate = true;
    } else if (arg === '--email' || arg === '-e') {
      options.email = args[++i] || '';
    } else if (arg === '--password' || arg === '-p') {
      options.password = args[++i] || '';
    } else if (arg === '--help' || arg === '-h') {
      options.help = true;
    }
  }

  return options;
}

async function main() {
  const options = parseArgs();

  if (options.help) {
    console.log(`
SamplingHub Admin Credential Generator
Usage:
  node scripts/setup_admin_credentials.js [options]

Options:
  --generate, -g               Generate credentials non-interactively
  --email <email>, -e <email>  Set administrator email (used with --generate)
  --password <pass>, -p <pass> Set password directly (used with --generate)
  --help, -h                   Show this help message

Examples:
  Interactive guided setup:
    node scripts/setup_admin_credentials.js

  Non-interactive auto-generation:
    node scripts/setup_admin_credentials.js --generate --email owner@samplinghub.world
`);
    process.exit(0);
  }

  console.log('\n================================================================');
  console.log('   SAMPLINGHUB — FIRST ADMINISTRATOR ACCOUNT SETUP GENERATOR    ');
  console.log('================================================================\n');

  let adminEmail = options.email ? options.email.toLowerCase().trim() : '';
  let pass1 = options.password || '';
  let autoGeneratedPassword = false;

  if (options.generate) {
    if (!adminEmail) {
      adminEmail = 'owner@samplinghub.world';
    }
    if (!pass1) {
      pass1 = crypto.randomBytes(18).toString('base64url');
      autoGeneratedPassword = true;
    }
  } else {
    // Step 1: Owner-Chosen Administrator Email
    while (!adminEmail) {
      const emailInput = await askQuestion('Enter your Administrator Email address: ');
      if (emailInput && emailInput.includes('@') && emailInput.includes('.')) {
        adminEmail = emailInput.toLowerCase().trim();
      } else {
        console.log('Please enter a valid email address (e.g., owner@samplinghub.world or your chosen address).\n');
      }
    }

    // Step 2: Password with masking
    console.log('\nEnter your private administrator password.');
    console.log('(Input is masked with asterisks and will NOT be written to any file):');
    pass1 = await askHiddenQuestion('Enter Password: ');

    if (!pass1 || pass1.length < 8) {
      console.error('\n[ERROR] Password must be at least 8 characters in length for security.');
      process.exit(1);
    }

    const pass2 = await askHiddenQuestion('Confirm Password: ');

    if (pass1 !== pass2) {
      console.error('\n[ERROR] Passwords do not match. Please run the script again.');
      process.exit(1);
    }
  }

  // Step 3: Compute standard RFC 7914 scrypt password hash with 16-byte random salt
  const salt = crypto.randomBytes(16).toString('hex');
  const N = 16384;
  const r = 8;
  const p = 1;
  const keylen = 64;
  const derivedKey = crypto.scryptSync(pass1, salt, keylen, { N, r, p });
  // Standard Modular Crypt Format: $scrypt$N=16384,r=8,p=1$<salt-hex>$<hash-hex>
  const passwordHash = `$scrypt$N=${N},r=${r},p=${p}$${salt}$${derivedKey.toString('hex')}`;

  // Step 4: Generate a high-entropy 64-character hex session secret
  const sessionSecret = crypto.randomBytes(32).toString('hex');

  console.log('\n================================================================');
  console.log('           ADMIN CREDENTIALS GENERATED SUCCESSFULLY             ');
  console.log('================================================================\n');
  if (autoGeneratedPassword) {
    console.log(`Auto-generated Temporary Password:  ${pass1}`);
    console.log('IMPORTANT: Record this password in a secure password manager now.\n');
  }
  console.log(`Configured Administrator Email:  ${adminEmail}\n`);
  console.log('Add the following THREE environment variables to your Vercel Project:');
  console.log('(Go to: Vercel Dashboard -> SwatchCraftIndia -> Settings -> Environment Variables)\n');
  console.log('----------------------------------------------------------------');
  console.log('VARIABLE 1:');
  console.log('Name:   ADMIN_EMAIL');
  console.log(`Value:  ${adminEmail}`);
  console.log('Target: Production, Preview, Development (Select all 3)');
  console.log('----------------------------------------------------------------');
  console.log('VARIABLE 2:');
  console.log('Name:   ADMIN_PASSWORD_HASH');
  console.log(`Value:  ${passwordHash}`);
  console.log('Target: Production, Preview, Development (Select all 3)');
  console.log('----------------------------------------------------------------');
  console.log('VARIABLE 3:');
  console.log('Name:   ADMIN_SESSION_SECRET');
  console.log(`Value:  ${sessionSecret}`);
  console.log('Target: Production, Preview, Development (Select all 3)');
  console.log('----------------------------------------------------------------\n');
  console.log('NEXT STEPS:');
  console.log('1. Copy VARIABLE 1, 2, and 3 into your Vercel Project Settings.');
  console.log('2. Redeploy the latest commit in Vercel to activate the new environment variables.');
  console.log(`3. Navigate to https://www.samplinghub.world/admin and log in with ${adminEmail}`);
  console.log('   using the private password.\n');
}

main().catch((err) => {
  console.error('\nFatal error generating credentials:', err);
  process.exit(1);
});
